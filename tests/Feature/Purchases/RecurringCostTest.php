function recurringBillPayload($test, array $overrides = []): array
{
    $bill = purchaseBillPayload($test, 5000);

    return [
        'name' => 'Office rent',
        'supplier_id' => $test->supplier->id,
        'mode' => 'BILL',
        'frequency' => '0 0 1 * *',
        'starts_at' => '2026-06-15',
        'limit_by' => 'NONE',
        'due_days' => 14,
        'template' => ['currency_id' => $bill['currency_id'], 'exchange_rate' => 1, 'items' => $bill['items']],
        ...$overrides,
    ];
}

/**
 * A schedule whose next run is set back, as if the scheduler had been down.
 */
function overdueSchedule($test, array $overrides = [], string $nextRun = '2026-04-01 00:00:00'): RecurringCost
{
    $id = $test->postJson('/api/v1/recurring-costs', recurringBillPayload($test, $overrides))->assertSuccessful()->json('data.id');
    RecurringCost::query()->whereKey($id)->update(['next_run_at' => $nextRun]);

    return RecurringCost::findOrFail($id);
}

test('a new schedule first runs on its first occurrence from today', function () {
    $this->postJson('/api/v1/recurring-costs', recurringBillPayload($this))
        ->assertSuccessful()
        ->assertJsonPath('data.status', 'ACTIVE')
        ->assertJsonPath('data.next_run_at', '2026-07-01 00:00:00');

    $this->postJson('/api/v1/recurring-costs', recurringBillPayload($this, ['starts_at' => '2026-09-01']))
        ->assertJsonPath('data.next_run_at', '2026-09-01 00:00:00');
});

test('missed runs are each generated as a bill dated its own day', function () {
    $schedule = overdueSchedule($this);

    artisan('recurring-costs:generate')->assertSuccessful();

    $bills = Bill::query()->orderBy('document_date')->get();

    expect($bills->pluck('document_date')->all())->toBe(['2026-04-01', '2026-05-01', '2026-06-01'])
        ->and($bills->pluck('due_date')->all())->toBe(['2026-04-15', '2026-05-15', '2026-06-15'])
        ->and($bills->pluck('status')->unique()->all())->toBe(['OPEN'])
        ->and((int) $bills->first()->total)->toBe(5000)
        ->and($schedule->fresh()->next_run_at)->toBe('2026-07-01 00:00:00')
        ->and($schedule->occurrences()->count())->toBe(3);

    artisan('recurring-costs:generate')->assertSuccessful();

    expect(Bill::query()->count())->toBe(3);
});

test('draft mode creates bills to review first', function () {
