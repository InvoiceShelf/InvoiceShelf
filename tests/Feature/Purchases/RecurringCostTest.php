test('Manager can set up schedules and Read only can only see them', function () {
    app(RolePresetService::class)->applyDefaults();
    $member = function (string $role) {
        $user = User::factory()->create(['role' => 'user']);
        $user->companies()->attach($this->companyId);
        BouncerFacade::scope()->onceTo($this->companyId, fn () => $user->assign($role));
        BouncerFacade::refresh();

        return $user;
    };

    Sanctum::actingAs($member('preset:manager'));
    $this->postJson('/api/v1/recurring-costs', recurringBillPayload($this))->assertSuccessful();

    Sanctum::actingAs($member('preset:read-only'));
    $this->getJson('/api/v1/recurring-costs')->assertOk()->assertJsonCount(1, 'data');
    $this->postJson('/api/v1/recurring-costs', recurringBillPayload($this))->assertForbidden();
});

