test('a recurring expense is recorded as paid on its day', function () {
    overdueSchedule($this, [
        'mode' => 'EXPENSE',
        'template' => ['amount' => 1999, 'currency_id' => $this->currencyId, 'exchange_rate' => 1, 'expense_category_id' => $this->category->id],
    ], '2026-06-01 00:00:00');

    artisan('recurring-costs:generate')->assertSuccessful();

    $expense = Expense::query()->sole();

    expect($expense->expense_date)->toStartWith('2026-06-01')
        ->and((int) $expense->amount)->toBe(1999)
        ->and($expense->supplier_id)->toBe($this->supplier->id)
        ->and(Bill::query()->count())->toBe(0);
});

test('a count limit completes the schedule, and raising it reactivates it', function () {
    $schedule = overdueSchedule($this, ['limit_by' => 'COUNT', 'limit_count' => 2]);

    artisan('recurring-costs:generate')->assertSuccessful();

    expect(Bill::query()->count())->toBe(2)
        ->and($schedule->fresh()->status)->toBe('COMPLETED');

    // Months later the limit is raised: the schedule carries on from today
    // instead of making up the runs it sat out.
    Carbon::setTestNow('2026-09-15 12:00:00');
    $this->putJson('/api/v1/recurring-costs/'.$schedule->id, recurringBillPayload($this, ['limit_by' => 'COUNT', 'limit_count' => 5]))
        ->assertSuccessful()
        ->assertJsonPath('data.status', 'ACTIVE')
        ->assertJsonPath('data.next_run_at', '2026-10-01 00:00:00');

    artisan('recurring-costs:generate')->assertSuccessful();
    expect(Bill::query()->count())->toBe(2);
});

test('a paused schedule made active from the form skips the runs it sat out', function () {
    $schedule = overdueSchedule($this, ['status' => 'ON_HOLD']);

    $this->putJson('/api/v1/recurring-costs/'.$schedule->id, recurringBillPayload($this, ['status' => 'ACTIVE']))
        ->assertSuccessful()
        ->assertJsonPath('data.status', 'ACTIVE')
        ->assertJsonPath('data.next_run_at', '2026-07-01 00:00:00');

    artisan('recurring-costs:generate')->assertSuccessful();
    expect(Bill::query()->count())->toBe(0);
});

test('a paused schedule makes nothing, and resuming keeps today but skips the paused runs', function () {
    Carbon::setTestNow('2026-06-01 09:00:00');
    $schedule = overdueSchedule($this);

    $this->postJson('/api/v1/recurring-costs/'.$schedule->id.'/actions', ['action' => 'pause'])->assertJsonPath('data.status', 'ON_HOLD');
    artisan('recurring-costs:generate')->assertSuccessful();
    expect(Bill::query()->count())->toBe(0);

    $this->postJson('/api/v1/recurring-costs/'.$schedule->id.'/actions', ['action' => 'resume'])
        ->assertJsonPath('data.status', 'ACTIVE')
        ->assertJsonPath('data.next_run_at', '2026-06-01 00:00:00');
    artisan('recurring-costs:generate')->assertSuccessful();

    expect(Bill::query()->sole()->document_date)->toBe('2026-06-01');
});

test('a failing run keeps its day, emails the creator once and recovers', function () {
    Mail::fake();
    $schedule = overdueSchedule($this, ['notify_creator' => true], '2026-06-01 00:00:00');
    $this->supplier->update(['enabled' => false]);

    artisan('recurring-costs:generate')->assertSuccessful();

    expect(Bill::query()->count())->toBe(0)
        ->and($schedule->fresh()->last_error)->toBe('purchase_supplier_inactive')
        ->and($schedule->fresh()->next_run_at)->toBe('2026-06-01 00:00:00');
    Mail::assertSent(RecurringCostFailedMail::class, fn ($mail) => $mail->hasTo($this->user->email));

    // Within the hour it is left alone; after it, it is tried again without a second email.
    Carbon::setTestNow('2026-06-15 12:30:00');
    artisan('recurring-costs:generate')->assertSuccessful();
    Carbon::setTestNow('2026-06-15 14:00:00');
    artisan('recurring-costs:generate')->assertSuccessful();
    Mail::assertSent(RecurringCostFailedMail::class, 1);

    $this->supplier->update(['enabled' => true]);
    Carbon::setTestNow('2026-06-15 16:00:00');
    artisan('recurring-costs:generate')->assertSuccessful();

    expect(Bill::query()->count())->toBe(1)
        ->and($schedule->fresh()->last_error)->toBeNull();
    Mail::assertSent(RecurringCostGeneratedMail::class, fn ($mail) => $mail->hasTo($this->user->email));
});

